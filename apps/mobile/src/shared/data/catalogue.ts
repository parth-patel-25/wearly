/**
 * Prototype catalogue.
 *
 * Every piece here is invented. There are no real listings, no real lenders and
 * no real people behind these names — the UI says so in a few places and the
 * README says so in one. What they are for is exercising the layout, the
 * progressive disclosure and the rental flow with enough volume to find out
 * whether a fifty-item grid still feels calm.
 *
 * The catalogue is generated from a handful of name/price seeds rather than
 * written out fifty times, because hand-written duplicate rows drift apart and
 * a grid where every card has a subtly different shape is very hard to design
 * against.
 *
 * The names, lenders and prices are invented; the photographs are not, but they
 * are borrowed — they are stock stand-ins from DummyJSON, regenerated by
 * `bun run images:generate`. See `catalogue-images.generated.ts`.
 */

import type { Listing } from "@wearly/shared/api/types";
import type { Condition } from "@wearly/shared/enums";
import type { PlaceholderTone } from "@wearly/ui-native/media";

export { CONDITION_VALUES } from "@wearly/shared/enums";
export type { Condition };

export const CATALOGUE_DISCLAIMER =
  "Prototype catalogue. Every item, lender and price here is invented for design review.";

/** The human labels live here: they describe display, not storage. */
export const CONDITION_LABEL = {
  brand_new_with_tags: "Brand New with Tags",
  brand_new_without_tags: "Brand New without Tags",
  excellent: "Excellent",
  good: "Good",
  fair: "Fair",
} as const satisfies Record<Condition, string>;

/** The label for a stored condition, or the honest "not said" case. */
export function conditionLabel(condition: Condition | null): string {
  return condition === null ? "Not stated" : CONDITION_LABEL[condition];
}

export type Category =
  | "Dresses"
  | "Ethnic"
  | "Jackets"
  | "Sets"
  | "Shirts"
  | "Trousers";

export interface Lender {
  /** Lender photo from the API; null when none was shared. */
  image: string | null;
  name: string;
  neighbourhood: string;
  /** Kept in the data so the product page can say "verification is not part of this prototype" honestly. */
  verified: boolean;
}

export interface Piece {
  /** Public neighbourhood label. The exact address never exists on a Piece. */
  areaLabel: string;
  /** Already rounded by the API; null when the renter shared no location. */
  distanceBand: string | null;
  availableFrom: string;
  category: Category;
  /** Null when the lender never said — never a guessed label. */
  condition: Condition | null;
  /** The API state: "published" or "draft". */
  status: Listing["status"];
  /** Rupees per day. */
  dailyRate: number;
  deposit: number;
  description: string;
  /**
   * Placeholder hues, one per gallery slot. These are what a media block shows
   * before its photograph arrives — not the imagery itself.
   */
  gallery: readonly PlaceholderTone[];
  id: string;
  /** All photos of the piece (cover first). */
  images: readonly string[];
  lender: Lender;
  name: string;
  /** The lender's stated size, used by the size filter and the fit section. */
  size: string;
  /** ISO date the piece is already committed and cannot be rented. */
  unavailable: readonly string[];
}

